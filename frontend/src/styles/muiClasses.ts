export function cx(...values: unknown[]): string {
  const classes: string[] = [];
  const visit = (value: unknown) => {
    if (!value) return;
    if (Array.isArray(value)) return value.forEach(visit);
    if (typeof value === 'object') {
      for (const [name, enabled] of Object.entries(value as Record<string, unknown>)) if (enabled) visit(name);
      return;
    }
    for (const name of String(value).trim().split(/\s+/)) {
      if (name) classes.push(utilityClasses[name] || name);
    }
  };
  values.forEach(visit);
  return classes.join(' ');
}
